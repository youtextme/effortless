#!/usr/bin/env node
/**
 * Bake Kindle-style passage bodies into words.js (350–450 words, 4 targets × ≥5).
 * Run from repo root: node wordspark/scripts/generate-passages.mjs
 *
 * Reads card vocabulary (day/theme/takeaway/words), writes static passage DB with body.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { VOCABULARY as SOURCE } from '../js/data/words.js';
import {
  generatePassagePages,
  getTargetWords,
  validatePassage,
  passageWordCount,
  TARGET_WORDS_PER_PASSAGE,
  MIN_WORD_OCCURRENCES,
  PASSAGE_WORD_MIN,
  PASSAGE_WORD_MAX,
} from '../js/passage-generator.js';
import { getTopicTitle } from '../js/data/topics.js';

const here = dirname(fileURLToPath(import.meta.url));

function bakePassage(entry) {
  const card = {
    day: entry.day,
    theme: entry.theme,
    takeaway: entry.takeaway,
    words: entry.words,
  };
  const { h1, sections } = generatePassagePages(card);
  const body = sections.map((s) => s.body).join('\n\n');
  const body_wc = passageWordCount(sections);
  const targets = getTargetWords(card).map((w) => w.word);
  return {
    day: card.day,
    theme: card.theme,
    takeaway: card.takeaway,
    title: h1 || getTopicTitle(card.day),
    body,
    body_wc,
    targets,
    words: card.words,
  };
}

function main() {
  const passages = [];
  const failures = [];

  for (const entry of SOURCE) {
    const baked = bakePassage(entry);
    const check = validatePassage({
      day: entry.day,
      theme: entry.theme,
      takeaway: entry.takeaway,
      words: entry.words,
    });
    if (!check.ok) failures.push({ day: entry.day, issues: check.issues });
    if (baked.body_wc < PASSAGE_WORD_MIN || baked.body_wc > PASSAGE_WORD_MAX) {
      failures.push({ day: entry.day, issues: [`body_wc ${baked.body_wc} outside range`] });
    }
    if (baked.targets.length !== TARGET_WORDS_PER_PASSAGE) {
      failures.push({ day: entry.day, issues: [`expected ${TARGET_WORDS_PER_PASSAGE} targets`] });
    }
    passages.push(baked);
  }

  if (failures.length) {
    console.error('Passage bake failures:', failures.slice(0, 5));
    process.exit(1);
  }

  const outPath = join(here, '..', 'js', 'data', 'words.js');
  const lines = [
    '/**',
    ' * WordSpark passage database — 100 Kindle-style readings.',
    ` * Each passage: ${PASSAGE_WORD_MIN}–${PASSAGE_WORD_MAX} words, ${TARGET_WORDS_PER_PASSAGE} targets × ≥${MIN_WORD_OCCURRENCES} occurrences.`,
    ' * Generated by scripts/generate-passages.mjs — do not hand-edit.',
    ' */',
    '',
    `export const VOCABULARY = ${JSON.stringify(passages, null, 2)};`,
    'export const TOTAL_DAYS = 100;',
    'export const WORDS_PER_DAY = 10;',
    `export const TOTAL_WORDS = ${passages.reduce((n, p) => n + p.words.length, 0)};`,
    '',
  ];
  writeFileSync(outPath, lines.join('\n'), 'utf8');
  console.log(`Wrote ${passages.length} passages → ${outPath}`);
  console.log(`body_wc range: ${Math.min(...passages.map((p) => p.body_wc))}–${Math.max(...passages.map((p) => p.body_wc))}`);
}

main();
